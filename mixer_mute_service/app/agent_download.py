"""One-file update for the desktop display agent, downloadable from the web UI.

GET /desktop/agent/update.cmd returns a .cmd that carries the agent files of
this service's own release (desktop_agent/ next to the .exe, or the source tree
in development). Double-clicked on a display PC, it runs
desktop_agent/update-agent.ps1 with those files: replace the installed agent's
files, restart it, check that port 8766 answers; or the first install via
install-agent.ps1 when no agent is installed yet.

So updating the agent no longer means downloading and unpacking the release:
open the web UI on the display PC, click "Agent-Update", run the file.
"""

from __future__ import annotations

import base64
import re
import sys
from pathlib import Path
from typing import Optional

from fastapi import APIRouter, Request
from fastapi.responses import JSONResponse, Response

from . import updater

router = APIRouter()

FILE_NAME = "MixerDisplayAgent-Update.cmd"
SCRIPT_NAME = "update-agent.ps1"
AGENT_SUFFIXES = (".py", ".txt", ".ps1")
MARKER = "##POWERSHELL"

# cmd.exe only runs these lines; it never reads past "exit /b". PowerShell then
# runs everything from the marker on. The command line spells the marker as
# '#' + '#POWERSHELL' so that its own text is not found first.
CMD_HEADER = """@echo off
rem Mixer display agent: update or first install. Generated by the Mixer Mute Service.
set "MIXER_AGENT_CMD=%~f0"
powershell.exe -NoProfile -ExecutionPolicy Bypass -Command "$t = [IO.File]::ReadAllText($env:MIXER_AGENT_CMD); Invoke-Expression $t.Substring($t.IndexOf('#' + '#POWERSHELL'))"
echo.
pause
exit /b
"""


def agent_dir() -> Path:
    if getattr(sys, "frozen", False):
        # The release build copies desktop_agent/ next to the .exe.
        return Path(sys.executable).parent / "desktop_agent"
    return Path(__file__).resolve().parent.parent / "desktop_agent"


def _agent_files(directory: Path) -> list:
    return sorted(
        p for p in directory.iterdir()
        if p.is_file() and p.suffix in AGENT_SUFFIXES and not p.name.startswith(".")
    )


def _ps_string(value: str) -> str:
    return '"' + value.replace("`", "``").replace('"', '`"').replace("$", "`$") + '"'


def build_update_cmd(directory: Path, version: str) -> bytes:
    """The .cmd as bytes (UTF-8 without BOM, CRLF line endings)."""
    script = (directory / SCRIPT_NAME).read_text(encoding="utf-8")
    entries = "\n".join(
        f"    {_ps_string(p.name)} = \"{base64.b64encode(p.read_bytes()).decode('ascii')}\""
        for p in _agent_files(directory)
    )
    text = (
        CMD_HEADER
        + MARKER + "\n"
        + f"$AgentVersion = {_ps_string(version)}\n"
        + "$AgentFiles = @{\n" + entries + "\n}\n"
        + script
    )
    return text.replace("\r\n", "\n").replace("\n", "\r\n").encode("utf-8")


def _version(request: Request) -> str:
    raw: Optional[str] = updater._installed_release() or getattr(request.app.state, "build_id", None)
    return re.sub(r"[^A-Za-z0-9._+-]", "", raw or "") or "dev"


@router.get("/desktop/agent/update.cmd")
async def agent_update_cmd(request: Request):
    directory = agent_dir()
    if not (directory / SCRIPT_NAME).is_file():
        return JSONResponse({"ok": False, "reason": "display agent files are not part of this installation"}, 404)
    return Response(
        build_update_cmd(directory, _version(request)),
        media_type="application/octet-stream",
        headers={"Content-Disposition": f'attachment; filename="{FILE_NAME}"'},
    )
